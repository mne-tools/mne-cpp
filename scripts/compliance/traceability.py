# @brief    Class-to-test traceability of the public API from doc/api_registry.json.
"""Class-to-test traceability of the public API.

``doc/api_registry.json`` names, for every public class, the test that covers it and its example. This tool
turns that into a traceability matrix per library (``doc/compliance/traceability.json``) and a documentation page
(``doc/website/docs/development/traceability.mdx``), and enforces two rules with ``--check``:

* every named test exists in ``src/tests``;
* per library, the number of classes with a named test never falls below its floor in ``traceability_policy.json``
  (a ratchet: raise the floor in the commit that adds tests). Libraries marked safety-relevant there are listed
  first and must reach full traceability before a release that claims IEC 62304 class B.

Usage
-----
    python3 scripts/compliance/traceability.py            # rewrite the committed files
    python3 scripts/compliance/traceability.py --check
    python3 scripts/compliance/traceability.py --print-floors
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
REGISTRY = Path("doc/api_registry.json")
POLICY = Path(__file__).resolve().parent / "traceability_policy.json"
OUTPUTS = {"json": Path("doc/compliance/traceability.json"),
           "mdx": Path("doc/website/docs/development/traceability.mdx")}


def matrix(registry: dict[str, Any], root: Path = REPO_ROOT) -> dict[str, Any]:
    modules: dict[str, dict[str, Any]] = defaultdict(lambda: {"classes": 0, "tested": 0, "untested": [],
                                                              "missing_tests": []})
    for item in sorted(registry["classes"], key=lambda c: (c["module"], c["name"])):
        module = modules[item["module"]]
        module["classes"] += 1
        if item.get("test"):
            module["tested"] += 1
            if not (root / "src" / "tests" / item["test"]).is_dir():
                module["missing_tests"].append(f"{item['name']} -> {item['test']}")
        else:
            module["untested"].append(item["name"])
    return {"generated_by": "scripts/compliance/traceability.py", "source": str(REGISTRY),
            "modules": dict(sorted(modules.items()))}


def problems(report: dict[str, Any], policy: dict[str, Any]) -> list[str]:
    found = []
    for name, module in report["modules"].items():
        found += [f"{name}: {entry} does not exist in src/tests" for entry in module["missing_tests"]]
        floor = policy["floors"].get(name, 0)
        if module["tested"] < floor:
            found.append(f"{name}: {module['tested']} classes with a test, below its floor of {floor}")
    return found


def render_mdx(report: dict[str, Any], policy: dict[str, Any]) -> str:
    safety = set(policy["safety_relevant"])
    order = sorted(report["modules"], key=lambda m: (m not in safety, m))
    total = sum(m["classes"] for m in report["modules"].values())
    tested = sum(m["tested"] for m in report["modules"].values())
    lines = ["---", "id: traceability", 'title: "Traceability"', "sidebar_label: Traceability", "---", "",
             "{/* Generated by scripts/compliance/traceability.py from doc/api_registry.json. Do not edit. */}", "",
             "# Class-to-test traceability", "",
             f"{tested} of {total} public classes name the test that covers them in "
             "[`doc/api_registry.json`](https://github.com/mne-tools/mne-cpp/blob/staging/doc/api_registry.json). "
             "CI checks that every named test exists and that no library's count falls below its floor in "
             "`scripts/compliance/traceability_policy.json`. Libraries in the acquisition, processing and file "
             "path are marked safety-relevant and come first.", "",
             "| Library | Safety-relevant | Classes | With a test | Share |", "|---|---|---:|---:|---:|"]
    for name in order:
        module = report["modules"][name]
        share = 100.0 * module["tested"] / module["classes"] if module["classes"] else 100.0
        lines.append(f"| {name} | {'yes' if name in safety else 'no'} | {module['classes']} | {module['tested']} "
                     f"| {share:.0f} % |")
    lines += ["", "## Classes without a named test", ""]
    for name in order:
        untested = report["modules"][name]["untested"]
        if untested:
            lines.append(f"- **{name}**: " + ", ".join(f"`{c}`" for c in untested))
    return "\n".join(lines) + "\n"


def render(root: Path = REPO_ROOT) -> tuple[dict[Path, str], list[str]]:
    registry = json.loads((root / REGISTRY).read_text(encoding="utf-8"))
    policy = json.loads(POLICY.read_text(encoding="utf-8"))
    report = matrix(registry, root)
    files = {OUTPUTS["json"]: json.dumps(report, indent=2) + "\n", OUTPUTS["mdx"]: render_mdx(report, policy)}
    return files, problems(report, policy)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if a file is stale or a rule is broken")
    parser.add_argument("--print-floors", action="store_true", help="print the current counts as floors")
    args = parser.parse_args(argv)

    files, found = render(REPO_ROOT)
    if args.print_floors:
        report = json.loads(files[OUTPUTS["json"]])
        print(json.dumps({name: m["tested"] for name, m in report["modules"].items()}, indent=2))
        return 0
    if args.check:
        found += [f"{path} is stale; run scripts/compliance/traceability.py" for path, text in files.items()
                  if not (REPO_ROOT / path).exists() or (REPO_ROOT / path).read_text(encoding="utf-8") != text]
    else:
        for path, text in files.items():
            (REPO_ROOT / path).parent.mkdir(parents=True, exist_ok=True)
            (REPO_ROOT / path).write_text(text, encoding="utf-8")
            print(f"wrote {path}")
    for problem in found:
        print(f"FAIL: {problem}")
    if args.check and not found:
        print("PASS: every named test exists and no library is below its traceability floor.")
    return 1 if found else 0


if __name__ == "__main__":
    raise SystemExit(main())
