# @brief    Render the purple traces at the foot of the installer's step panel.
"""Render the purple traces at the foot of the installer's step panel.

The traces follow the website's light hero (doc/website/src/pages/index.tsx)
and fade out towards the page list above them. style.qss paints them as the
background of the step panel. The images and config/hero.qrc are committed and
compiled into the installer with ``binarycreator -r config/hero.qrc``. Needs
rsvg-convert.

Usage
-----
    python3 scripts/packaging/installer/render_waves.py
"""

from __future__ import annotations

import math
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "config" / "hero"
QRC = HERE / "config" / "hero.qrc"

# The step panel is as wide as sidebar.png
SIZE = (200, 170)
# (baseline as a fraction of the height, amplitude, harmonics, stroke, opacity)
TRACES = [
    (0.42, 0.10, (2, 5), 1.0, 0.30),
    (0.52, 0.14, (1, 3), 1.6, 0.55),
    (0.62, 0.12, (2, 3), 1.2, 0.42),
    (0.72, 0.11, (1, 4), 1.6, 0.36),
    (0.82, 0.07, (3, 5), 1.2, 0.30),
]


def trace(width: float, height: float, spec: tuple, samples: int = 100) -> str:
    base, amp, harmonics, *_ = spec
    points = []
    for i in range(samples + 1):
        x = width * i / samples
        y = sum(math.sin(2 * math.pi * n * x / width + n) / k for k, n in enumerate(harmonics, start=1))
        points.append(f"{x:.1f},{height * (base + amp * y / len(harmonics)):.1f}")
    return "M" + " L".join(points)


def side_panel(width: int, height: int) -> str:
    paths = "".join(f'<path d="{trace(width, height, spec)}" fill="none" stroke="#6c5ce7" '
                    f'stroke-opacity="{spec[4]}" stroke-width="{spec[3]}" stroke-linecap="round"/>'
                    for spec in TRACES)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}">'
            '<defs><linearGradient id="fade" x1="0" y1="0" x2="0" y2="1">'
            '<stop offset="0.2" stop-color="#fff" stop-opacity="0"/><stop offset="0.6" stop-color="#fff"/>'
            '</linearGradient><mask id="m"><rect width="100%" height="100%" fill="url(#fade)"/></mask></defs>'
            f'<g mask="url(#m)">{paths}</g></svg>')


def main() -> int:
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("*"):
        old.unlink()
    with tempfile.TemporaryDirectory() as name:
        tmp = Path(name)
        (tmp / "side.svg").write_text(side_panel(*SIZE), encoding="utf-8")
        # Qt picks the @2x file on HiDPI screens
        for scale, suffix in ((1, ""), (2, "@2x")):
            subprocess.run(["rsvg-convert", "-w", str(SIZE[0] * scale), "-h", str(SIZE[1] * scale),
                            str(tmp / "side.svg"), "-o", str(OUT / f"side{suffix}.png")], check=True)
        (tmp / "check.svg").write_text(
            '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16"><path d="M4 8.5l2.6 2.6L12 5.6" '
            'fill="none" stroke="#fff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg>')
        subprocess.run(["rsvg-convert", "-w", "32", str(tmp / "check.svg"), "-o", str(OUT / "check.png")], check=True)
    files = ["hero/side.png", "hero/side@2x.png", "hero/check.png"]
    entries = "\n".join(f"        <file>{f}</file>" for f in files)
    QRC.write_text(f'<!DOCTYPE RCC>\n<!-- Generated by render_waves.py -->\n<RCC version="1.0">\n'
                   f'    <qresource prefix="/mnecpp">\n{entries}\n    </qresource>\n</RCC>\n', encoding="utf-8")
    print(f"Rendered the step panel traces into {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
