# @brief    Checksum manifest for committed parity fixtures (T7.4).
"""Checksum manifest for the committed test fixtures under ``src/testframes/*/data``.

``fixtures.json`` lists, per test directory, the scripts that generate its
fixtures and the SHA-256 of every committed fixture file.  ``--check`` fails
when a fixture changed without regenerating the manifest, when a committed
fixture is not in the manifest, or when a listed file or generator is gone.
Fixtures are only ever regenerated by hand, in the pinned environment of
``reference_lock.json``; normal CI only reads them.

Usage
-----
    python3 tools/parity/check_fixtures.py --check     # CI
    python3 tools/parity/check_fixtures.py --list      # generators, for regeneration
    python3 tools/parity/check_fixtures.py --update    # after regenerating fixtures
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
MANIFEST = Path(__file__).resolve().parent / "fixtures.json"
TESTFRAMES = "src/testframes"


def tracked(repo_root: Path) -> list[str]:
    out = subprocess.run(["git", "ls-files", TESTFRAMES], cwd=repo_root, check=True,
                         capture_output=True, text=True).stdout
    return sorted(out.split())


def is_generator(path: str) -> bool:
    name = Path(path).name
    return name.endswith(".py") and name.startswith(("make_", "generate_"))


def build_manifest(repo_root: Path, files: list[str] | None = None) -> dict:
    files = tracked(repo_root) if files is None else files
    tests: dict[str, dict] = {}
    for path in files:
        parts = Path(path).parts
        if len(parts) < 4:
            continue
        test = parts[2]
        if is_generator(path):
            tests.setdefault(test, {"generators": [], "fixtures": {}})["generators"].append(path)
        elif len(parts) >= 5 and parts[3] == "data" and not path.endswith(".py"):
            digest = hashlib.sha256((repo_root / path).read_bytes()).hexdigest()
            tests.setdefault(test, {"generators": [], "fixtures": {}})["fixtures"][path] = digest
    return {
        "$comment": "Generated by tools/parity/check_fixtures.py --update. SHA-256 of every committed "
                    "fixture under src/testframes/*/data, with the scripts that generate them.",
        "tests": {name: tests[name] for name in sorted(tests) if tests[name]["fixtures"]},
    }


def compare(expected: dict, actual: dict) -> list[str]:
    problems: list[str] = []
    want, have = expected.get("tests", {}), actual["tests"]
    for test in sorted(set(want) | set(have)):
        w = want.get(test, {"generators": [], "fixtures": {}})
        h = have.get(test, {"generators": [], "fixtures": {}})
        regenerate = ", ".join(h["generators"] or w["generators"]) or "no generator; hand-made input"
        for path in sorted(set(w["fixtures"]) | set(h["fixtures"])):
            if path not in h["fixtures"]:
                problems.append(f"{path}: listed in the manifest but not committed")
            elif path not in w["fixtures"]:
                problems.append(f"{path}: committed but not in the manifest (run --update)")
            elif w["fixtures"][path] != h["fixtures"][path]:
                problems.append(f"{path}: content differs from the manifest; regenerate with {regenerate} "
                                "in the pinned environment, then run --update")
        for generator in sorted(set(w["generators"]) ^ set(h["generators"])):
            problems.append(f"{generator}: generator list differs from the manifest (run --update)")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail if fixtures and manifest disagree")
    mode.add_argument("--update", action="store_true", help="rewrite the manifest from the committed fixtures")
    mode.add_argument("--list", action="store_true", help="print the fixture generators")
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT)
    parser.add_argument("--manifest", type=Path, default=MANIFEST)
    args = parser.parse_args(argv)

    actual = build_manifest(args.repo_root)
    if args.list:
        for test, entry in actual["tests"].items():
            for generator in entry["generators"]:
                print(generator)
        return 0
    if args.update:
        args.manifest.write_text(json.dumps(actual, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {args.manifest}")
        return 0
    expected = json.loads(args.manifest.read_text(encoding="utf-8")) if args.manifest.is_file() else {}
    problems = compare(expected, actual)
    for problem in problems:
        print(f"FAIL: {problem}", file=sys.stderr)
    if problems:
        return 1
    count = sum(len(entry["fixtures"]) for entry in actual["tests"].values())
    print(f"OK: {count} fixtures in {len(actual['tests'])} tests match the manifest.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
