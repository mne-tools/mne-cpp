#include "numeric.h"

//=============================================================================================================
// USED NAMESPACES
//=============================================================================================================

using namespace SCMEASLIB;

//=============================================================================================================
// DEFINE MEMBER METHODS
//=============================================================================================================

Numeric::Numeric(QObject *parent)
: Measurement(QMetaType::fromName("Numeric::SPtr").id(), parent)
, m_qString_Unit("")
, m_dValue(-1)
{
}

//=============================================================================================================

Numeric::~Numeric()
{
}

//=============================================================================================================

void Numeric::setValue(double v)
{
    m_qMutex.lock();
    m_dValue = v;
    m_qMutex.unlock();
    emit notify();
}

//=============================================================================================================

double Numeric::getValue() const
{
    QMutexLocker locker(&m_qMutex);
    return m_dValue;
}
