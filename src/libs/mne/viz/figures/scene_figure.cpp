//=============================================================================================================

int SceneFigure::add_listener(std::function<void(Change)> listener)
{
    const int id = m_nextListener++;
    m_listeners.emplace(id, std::move(listener));
    return id;
}

//=============================================================================================================

void SceneFigure::remove_listener(int id)
{
    m_listeners.erase(id);
}

//=============================================================================================================

void SceneFigure::changed(Change change) const
{
    // A listener may remove itself or others
    const auto listeners = m_listeners;
    for (const auto& [id, listener] : listeners) {
        if (listener) {
            listener(change);
        }
    }
}
